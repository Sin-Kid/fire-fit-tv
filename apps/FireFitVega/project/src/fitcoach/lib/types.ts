// Copy of backend/src/types.ts. Keep the two in sync.

export type Goal = 'strength' | 'cardio' | 'mobility' | 'fat-burn';
export type Level = 'beginner' | 'intermediate' | 'advanced';
export type Equipment = 'none' | 'dumbbells' | 'resistance-band' | 'kettlebell' | 'yoga-mat';
export type Phase = 'warmup' | 'main' | 'cooldown';

export type Sex = 'male' | 'female' | 'unspecified';

/** Body data for the calorie estimate. Stays on the TV; never sent to the backend. */
export interface Profile {
  weightKg: number;
  heightCm: number;
  age: number;
  sex: Sex;
}

export interface WorkoutRequest {
  goal: Goal;
  minutes: number;
  level: Level;
  equipment: Equipment[];
  /** Optional free text, e.g. "sore knees" or "quiet, apartment friendly". */
  notes?: string;
}

export interface Exercise {
  name: string;
  phase: Phase;
  durationSec: number;
  restSec: number;
  /** One short form cue shown big on the TV. */
  cue: string;
  /** Easier variation for people who need it. */
  easier: string;
  /** Rough intensity 1-5, drives the colour bar on screen. */
  intensity: number;
}

export interface Workout {
  id: string;
  title: string;
  coachIntro: string;
  totalSec: number;
  exercises: Exercise[];
  /** 'bedrock' when generated by the model, 'fallback' when the offline generator was used. */
  source: 'bedrock' | 'fallback';
  model?: string;
}

export const GOALS: Goal[] = ['strength', 'cardio', 'mobility', 'fat-burn'];
export const LEVELS: Level[] = ['beginner', 'intermediate', 'advanced'];
export const EQUIPMENT: Equipment[] = ['none', 'dumbbells', 'resistance-band', 'kettlebell', 'yoga-mat'];
